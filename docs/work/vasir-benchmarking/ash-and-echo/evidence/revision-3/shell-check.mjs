import { chromium } from '/tmp/cloudbreak-playwright-validation/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];const failed=[];
page.on('pageerror',e=>errors.push(String(e)));
page.on('response',r=>{if(r.status()>=400)failed.push({url:r.url(),status:r.status()});});
await page.goto('http://127.0.0.1:8317/');
await page.waitForFunction(()=>window.__echo&&!document.querySelector('#start-button').disabled);
assert.equal(await page.locator('#game-hud').evaluate(e=>e.inert),true);
assert.equal(await page.locator('#touch-controls').evaluate(e=>e.inert),true);
assert.match(await page.locator('#intro-controls').textContent(),/SPACE/);
await page.screenshot({path:'tmp/ash-and-echo/depth-pass/intro-desktop-final.png'});
await page.locator('#start-button').focus();await page.keyboard.press('Enter');
await page.waitForTimeout(650);
assert.equal(await page.locator('#intro').evaluate(e=>e.inert),true);
assert.equal(await page.locator('#touch-controls').evaluate(e=>e.inert),false);
assert.equal(await page.evaluate(()=>window.__echo.snapshot().state),'playing');
await page.keyboard.press('Escape');
assert.equal(await page.locator('#game-hud').evaluate(e=>e.inert),true);
assert.equal(await page.evaluate(()=>document.activeElement.id),'resume-button');
await page.keyboard.press('Shift+Tab');
assert.equal(await page.evaluate(()=>document.activeElement.id),'motion-setting');
await page.keyboard.press('Tab');
assert.equal(await page.evaluate(()=>document.activeElement.id),'resume-button');
await page.locator('#motion-setting').check();
await page.keyboard.press('Escape');
assert.equal(await page.evaluate(()=>window.__echo.snapshot().paused),false);
await page.keyboard.down('ArrowRight');await page.keyboard.down('Space');await page.waitForTimeout(250);await page.keyboard.up('Space');await page.keyboard.up('ArrowRight');
assert.ok(await page.evaluate(()=>window.__echo.game.maxAltitude)>75);
await page.screenshot({path:'tmp/ash-and-echo/depth-pass/play-desktop-final.png'});
const loaded=await page.evaluate(()=>Object.fromEntries(Object.entries(window.__echo.assets).map(([k,v])=>[k,[v.naturalWidth,v.naturalHeight]])));
assert.deepEqual(Object.keys(loaded).sort(),['background','corbel','depth-arch','hero','shrine','spider','stone']);
await page.keyboard.press('KeyR');
assert.equal(await page.evaluate(()=>window.__echo.snapshot().deaths),0);
const mobile=await browser.newPage({viewport:{width:320,height:568},deviceScaleFactor:2,isMobile:true,hasTouch:true});
await mobile.goto('http://127.0.0.1:8317/');await mobile.waitForFunction(()=>window.__echo&&!document.querySelector('#start-button').disabled);
await mobile.locator('#start-button').tap();await mobile.waitForTimeout(650);
const bounds=await mobile.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,controls:[...document.querySelectorAll('[data-control]')].map(e=>{const r=e.getBoundingClientRect();return {x:r.x,y:r.y,w:r.width,h:r.height,right:r.right,bottom:r.bottom};})}));
assert.equal(bounds.width,bounds.scrollWidth);
assert.ok(bounds.controls.every(r=>r.w>=44&&r.h>=44&&r.x>=0&&r.right<=320&&r.bottom<=568));
assert.ok(bounds.controls[1].right<bounds.controls[2].x);
await mobile.screenshot({path:'tmp/ash-and-echo/depth-pass/play-small-phone-final.png'});
assert.deepEqual(errors,[]);assert.deepEqual(failed,[]);
await fs.writeFile('tmp/ash-and-echo/depth-pass/shell-final.json',JSON.stringify({checkedAt:new Date().toISOString(),errors,failed,loaded,bounds,desktopKeyboard:true,pauseFocusTrap:true,gentlerEffectsToggle:true},null,2));
console.log(JSON.stringify({errors,failed,loaded,bounds},null,2));await browser.close();
