import { chromium } from '/tmp/cloudbreak-playwright-validation/node_modules/playwright/index.mjs';
import { mkdir, writeFile } from 'node:fs/promises';
const out = process.argv[2] || '/Users/erikhazzard/code/vasir/tmp/ash-and-echo/depth-pass/final-review';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const errors = [];
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, hasTouch: true, isMobile: true, recordVideo: { dir: out + '/video', size: { width: 390, height: 844 } } });
const page = await context.newPage();
page.on('pageerror', error => errors.push(String(error)));
await page.goto('http://127.0.0.1:8317', { waitUntil: 'networkidle' });
console.log(await page.locator('button').allTextContents());
await page.getByRole('button', { name: /Begin the ascent/ }).click();
await page.waitForTimeout(900);
await page.screenshot({ path: out + '/mobile-00-before.png' });
await page.keyboard.down('ArrowRight');
await page.keyboard.down('Space');
await page.waitForTimeout(240);
await page.screenshot({ path: out + '/mobile-01-input.png' });
await page.keyboard.up('ArrowRight');
await page.keyboard.up('Space');
await page.waitForTimeout(110);
await page.keyboard.down('Space');
await page.waitForTimeout(150);
await page.screenshot({ path: out + '/mobile-02-double-jump.png' });
await page.keyboard.up('Space');
await page.waitForTimeout(1050);
await page.screenshot({ path: out + '/mobile-03-after.png' });
console.log('Mobile after:', await page.locator('body').innerText());
await context.close();
const desktop = await browser.newContext({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 1 });
const desk = await desktop.newPage();
desk.on('pageerror', error => errors.push(String(error)));
await desk.goto('http://127.0.0.1:8317', { waitUntil: 'networkidle' });
await desk.getByRole('button', { name: /Begin the ascent/ }).click();
await desk.waitForTimeout(900);
await desk.screenshot({ path: out + '/desktop-00-before.png' });
await desk.keyboard.down('ArrowRight');
await desk.keyboard.down('Space');
await desk.waitForTimeout(250);
await desk.screenshot({ path: out + '/desktop-01-active.png' });
await desk.keyboard.up('ArrowRight');
await desk.keyboard.up('Space');
await writeFile(out + '/capture-notes.json', JSON.stringify({ mode: 'Independent fixed-duration browser key presses, no product source or state snapshots used to choose input; no injected state or simulated time', mobile: { width:390, height:844, dpr:1 }, desktop: { width:1280, height:900, dpr:1 }, errors }, null, 2));
await desktop.close();
await browser.close();
console.log('Capture complete');
